// Preserve the original encode -> public decode construction as an independent
// authentication/normalization oracle for the private generated path.
func recordImagePublicReference(s Snapshot) (RecordImage, error) {
	present := s.Lifecycle.Recovery != nil
	sections := recordSections(&s)
	var records []StateRecord
	emit := func(tag int, body []byte) error {
		raw := frameStateRecord(tag, body)
		records = append(records, StateRecord{stateRecordKey(raw, 0), raw})
		return nil
	}
	if present {
		_ = emit(0, []byte("{}"))
	}
	for tag := 1; tag < len(sections); tag++ {
		if err := sections[tag].encode(func(raw []byte) error { return emit(tag, raw) }); err != nil {
			return RecordImage{}, err
		}
	}
	sort.Slice(records, func(i, j int) bool { return bytes.Compare(records[i].Key, records[j].Key) < 0 })
	var ordinal uint64
	for i := range records {
		if i > 0 && bytes.Equal(records[i-1].Raw, records[i].Raw) {
			ordinal++
		} else {
			ordinal = 0
		}
		binary.BigEndian.PutUint64(records[i].Key[32:], ordinal)
	}
	return DecodeRecordImage(records)
}

func TestRecordImageGeneratedMatchesPublicDecoder(t *testing.T) {
	_, nested := snapshotImageFixture(t, 2)
	nested.Lifecycle.Queries = []Query{{ID: "q", Space: "space", Owner: "owner", Version: 1, Input: []byte{}}}
	nested.Lifecycle.Recovery.Answers = []QueryAnswer{{Query: "q", Slot: "progress", Version: 1, Outcomes: []TaskOutcome{}}}
	for name, s := range map[string]Snapshot{
		"empty": {}, "recovery": {Lifecycle: LifecycleSnapshot{Recovery: &RecoverySnapshot{}}},
		"nested": nested,
		"escaped": {Lifecycle: LifecycleSnapshot{Queries: []Query{{ID: "q", Space: "s", Owner: "p", Version: 1,
			Status: "\"\\ufffd<>&\n\u2028\ufffd", Input: []byte("payload")}}}},
		"invalid-utf8":         {Lifecycle: LifecycleSnapshot{Queries: []Query{{ID: "q", Space: "s", Owner: "p", Version: 1, Status: string([]byte{0xff})}}}},
		"binary-decoder-limit": {Tasks: []Task{{ID: "t", Space: "s", Owner: "p", Goal: string(bytes.Repeat([]byte("g"), 1025)), GoalEpoch: 1, Status: TaskOpen}}},
		"relations":            {Executions: []Execution{{ID: "x", Task: "missing", Actor: "a", Incarnation: 1, AcceptedGoalEpoch: 1, Status: ExecutionReady}}},
	} {
		t.Run(name, func(t *testing.T) {
			want, wantErr := recordImagePublicReference(s)
			got, gotErr := EncodeRecordImage(s)
			if (wantErr == nil) != (gotErr == nil) || !errors.Is(gotErr, wantErr) {
				t.Fatalf("different validation: public=%v generated=%v", wantErr, gotErr)
			}
			if wantErr != nil {
				return
			}
			wantRecords, _ := want.Records()
			gotRecords, _ := got.Records()
			wantSnapshot, _ := want.Snapshot()
			gotSnapshot, _ := got.Snapshot()
			if !reflect.DeepEqual(gotRecords, wantRecords) || !reflect.DeepEqual(gotSnapshot, wantSnapshot) || got.Size() != want.Size() {
				t.Fatal("generated bytes or normalized state differ from public decoding")
			}
			mutateImageOwnedValue(reflect.ValueOf(&s).Elem())
			keys, err := got.RecordKeys()
			if err != nil {
				t.Fatal(err)
			}
			for i := range keys {
				record, err := got.RecordAt(i)
				if err != nil || !reflect.DeepEqual(record, wantRecords[i]) || !bytes.Equal(keys[i], record.Key) {
					t.Fatalf("selective record access: %v", err)
				}
				clear(keys[i])
				clear(record.Key)
				clear(record.Raw)
			}
			first, _ := got.Restore()
			second, _ := got.Restore()
			wantLedger, _ := want.Restore()
			mutateImageOwnedValue(reflect.ValueOf(&first.lifecycle).Elem())
			again, _ := got.Snapshot()
			againRecords, _ := got.Records()
			gotLedgerRaw := recordCanonical(t, second.Snapshot())
			wantLedgerRaw := recordCanonical(t, wantLedger.Snapshot())
			if !reflect.DeepEqual(again, wantSnapshot) || !bytes.Equal(gotLedgerRaw, wantLedgerRaw) ||
				!reflect.DeepEqual(againRecords, wantRecords) {
				t.Fatalf("ownership mismatch: image=%t ledger=%t records=%t",
					reflect.DeepEqual(again, wantSnapshot), bytes.Equal(gotLedgerRaw, wantLedgerRaw),
					reflect.DeepEqual(againRecords, wantRecords))
			}
			for _, index := range []int{-1, len(keys)} {
				if _, err := got.RecordAt(index); !errors.Is(err, ErrInvalid) {
					t.Fatal("invalid index accepted")
				}
			}
		})
	}
	var zero RecordImage
	if _, err := zero.RecordKeys(); !errors.Is(err, ErrInvalid) {
		t.Fatal("zero image returned keys")
	}
	if _, err := zero.RecordAt(0); !errors.Is(err, ErrInvalid) {
		t.Fatal("zero image returned record")
	}
}

func TestRecordGeneratedJSONBudgetMatchesPublic(t *testing.T) {
	answer := QueryAnswer{Query: "q", Slot: "progress", Version: 1, Outcomes: make([]TaskOutcome, 5000)}
	if recordAllocation(reflect.ValueOf(answer), 0) > MaxStateRecordBytes {
		t.Fatal("token fixture hit allocation preflight first")
	}
	s := Snapshot{Lifecycle: LifecycleSnapshot{
		Queries:  []Query{{ID: "q", Space: "s", Owner: "p", Version: 1}},
		Recovery: &RecoverySnapshot{Answers: []QueryAnswer{answer}},
	}}
	if _, err := EncodeRecordImage(s); !errors.Is(err, ErrStateLimit) {
		t.Fatalf("generated record lost token budget: %v", err)
	}
	if _, err := recordImagePublicReference(s); !errors.Is(err, ErrStateLimit) {
		t.Fatalf("public record token budget: %v", err)
	}
	for _, count := range []int{65534, 65535} {
		raw, err := json.Marshal(make([]int, count))
		if err != nil {
			t.Fatal(err)
		}
		want := boundedRecordJSON(raw)
		if got := boundedGeneratedRecordJSON(raw); !errors.Is(got, want) {
			t.Fatalf("token count %d: got %v want %v", count, got, want)
		}
	}
	for _, depth := range []int{31, 32, 33} {
		var value any = `"\\[]{},:<>` + "\n\u2028\ufffd"
		for i := 0; i < depth; i++ {
			value = []any{value}
		}
		raw, _ := json.Marshal(value)
		if got, want := boundedGeneratedRecordJSON(raw), boundedRecordJSON(raw); !errors.Is(got, want) {
			t.Fatalf("depth %d: got %v want %v", depth, got, want)
		}
	}
	raw, _ := json.Marshal([]any{nil, true, false, -1.25e-30, "", []byte{0xff}, map[string]any{"key": []any{}}})
	if err := boundedGeneratedRecordJSON(raw); err != nil {
		t.Fatal(err)
	}
}

func TestRecordJSONSchemaHasNoCustomCodecs(t *testing.T) {
	// Generated JSON may omit raw reauthentication only for the closed schema.
	// A future custom codec must explicitly revisit that trust boundary.
	hooks := []reflect.Type{
		reflect.TypeFor[json.Marshaler](), reflect.TypeFor[json.Unmarshaler](),
		reflect.TypeFor[encoding.TextMarshaler](), reflect.TypeFor[encoding.TextUnmarshaler](),
	}
	seen := map[reflect.Type]bool{}
	var visit func(reflect.Type)
	visit = func(typ reflect.Type) {
		if seen[typ] {
			return
		}
		seen[typ] = true
		for _, hook := range hooks {
			if typ.Implements(hook) || reflect.PointerTo(typ).Implements(hook) {
				t.Fatalf("custom record codec %v implements %v", typ, hook)
			}
		}
		switch typ.Kind() {
		case reflect.Pointer, reflect.Slice, reflect.Array:
			visit(typ.Elem())
		case reflect.Struct:
			for i := 0; i < typ.NumField(); i++ {
				visit(typ.Field(i).Type)
			}
		case reflect.Interface, reflect.Map:
			t.Fatalf("record schema is no longer closed: %v", typ)
		}
	}
	visit(reflect.TypeFor[LifecycleSnapshot]())
}

