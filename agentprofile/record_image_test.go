func TestRecordImageCanonicalAndRelations(t *testing.T) {
	s := Snapshot{Tasks: []Task{{ID: "t", Space: "s", Owner: "p", Goal: "g", GoalEpoch: 1, Status: TaskOpen}},
		Lifecycle: LifecycleSnapshot{Queries: []Query{{ID: "q", Space: "s", Owner: "p", Status: "open", Version: 1, Input: []byte("input")}}}}
	image, err := EncodeRecordImage(s)
	if err != nil {
		t.Fatal(err)
	}
	got, _ := image.Snapshot()
	gotImage, err := EncodeRecordImage(got)
	if err != nil {
		t.Fatal(err)
	}
	gotRecords, _ := gotImage.Records()
	wantRecords, _ := image.Records()
	if !reflect.DeepEqual(gotRecords, wantRecords) {
		t.Fatal("normalization diverged")
	}
	var query StateRecord
	records, _ := image.Records()
	for _, r := range records {
		if bytes.Contains(r.Raw, []byte(`"ID":"q"`)) {
			query = r
		}
	}
	if query.Raw == nil {
		t.Fatal("missing query record")
	}
	for name, raw := range map[string][]byte{
		"trailing":   append(bytes.Clone(query.Raw), 0),
		"whitespace": bytes.Replace(query.Raw, []byte(`{"ID"`), []byte(`{ "ID"`), 1),
		"unknown":    bytes.Replace(query.Raw, []byte(`{"ID"`), []byte(`{"extra":1,"ID"`), 1),
		"duplicate":  bytes.Replace(query.Raw, []byte(`{"ID"`), []byte(`{"ID":"other","ID"`), 1),
		"version":    append([]byte(recordDomain+"\x02"), query.Raw[len(recordDomain)+1:]...),
		"oversize":   make([]byte, MaxStateRecordBytes+1),
	} {
		t.Run(name, func(t *testing.T) {
			if err := ValidateStateRecord(raw); err == nil {
				t.Fatal("accepted noncanonical record")
			}
			// Supply a matching digest so this reaches the public schema decoder,
			// rather than failing only at the content-key check.
			if _, err := DecodeRecordImage([]StateRecord{{Key: stateRecordKey(raw, 0), Raw: raw}}); err == nil {
				t.Fatal("public image decoder accepted noncanonical record")
			}
		})
	}
	records[0].Key[0] ^= 1
	if _, err := DecodeRecordImage(records); err == nil {
		t.Fatal("accepted wrong content key")
	}
	bad := s
	bad.Executions = []Execution{{ID: "x", Task: "missing", Actor: "a", Incarnation: 1, AcceptedGoalEpoch: 1, Status: ExecutionReady}}
	if _, err := EncodeRecordImage(bad); err == nil {
		t.Fatal("bypassed cross-record validation")
	}
	if err := image.CheckScope("s", "other"); err == nil {
		t.Fatal("bypassed scope")
	}
}

