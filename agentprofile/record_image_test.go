func TestRecordImageSchemaCoverage(t *testing.T) {
	// This independent field-to-tag manifest must change deliberately whenever
	// the state schema changes. Merely extending a Go struct must fail this test.
	manifest := map[string]map[string]int{
		"Snapshot":  {"Tasks": 1, "Executions": 2, "Steps": 3, "Invocations": 4, "Actions": 5, "Lifecycle": -1},
		"Lifecycle": {"Queries": 6, "Activities": 7, "Attempts": 8, "Results": 9, "Messages": 10, "Consumptions": 11, "Continuations": 12, "Recovery": 0},
		"Recovery": {"Authorities": 13, "ActivitySpecs": 14, "ActivityControls": 15, "AttemptControls": 16,
			"Captures": 17, "Acceptances": 18, "Settlements": 19, "Reconciliations": 20, "Answers": 21,
			"Starts": 22, "TaskLinks": 23, "Goals": 24, "Outcomes": 25, "Actions": 26, "Resolutions": 27,
			"Resumes": 28, "Joins": 29, "Imports": 30, "ValidationRequirements": 31,
			"IdempotencyGuarantees": 32, "RetryAuthorizations": 33, "OutputChunks": 34},
	}
	container := func(s *Snapshot, name string) reflect.Value {
		switch name {
		case "Snapshot":
			return reflect.ValueOf(s).Elem()
		case "Lifecycle":
			return reflect.ValueOf(&s.Lifecycle).Elem()
		default:
			return reflect.ValueOf(s.Lifecycle.Recovery).Elem()
		}
	}
	_, seed := snapshotImageFixture(t, 1)
	seed.Actions = []PendingAction{{Key: "a", Generation: 1, Owner: seed.Executions[0].ID, Status: ActionPending,
		CommandDigest: digest('a'), Request: commandKey("a")}}
	seen := map[int]bool{0: true}
	for name, fields := range manifest {
		empty := Snapshot{Lifecycle: LifecycleSnapshot{Recovery: &RecoverySnapshot{}}}
		value := container(&empty, name)
		if value.NumField() != len(fields) {
			t.Fatalf("%s fields changed; explicitly extend record encoding and manifest", name)
		}
		for i := 0; i < value.NumField(); i++ {
			field := value.Type().Field(i)
			tag, ok := fields[field.Name]
			if !ok {
				t.Fatalf("uncovered %s.%s", name, field.Name)
			}
			if tag <= 0 {
				continue
			}
			if seen[tag] {
				t.Fatalf("duplicate tag %d", tag)
			}
			seen[tag] = true
			t.Run(name+"."+field.Name, func(t *testing.T) {
				input := Snapshot{Lifecycle: LifecycleSnapshot{Recovery: &RecoverySnapshot{}}}
				target := container(&input, name).FieldByName(field.Name)
				if tag <= 5 {
					target.Set(container(&seed, name).FieldByName(field.Name))
				} else {
					target.Set(reflect.MakeSlice(target.Type(), 1, 1))
				}
				sections := recordSections(&input)
				if len(sections) != 35 {
					t.Fatal("update manifest for new tags")
				}
				for j := 1; j < len(sections); j++ {
					count := 0
					err := sections[j].encode(func(raw []byte) error {
						count++
						if j != tag {
							t.Fatalf("field encoded under tag %d, want %d", j, tag)
						}
						out := Snapshot{}
						decodedTag, err := decodeStateRecord(frameStateRecord(j, raw), recordSections(&out))
						if err != nil || decodedTag != uint64(tag) {
							t.Fatalf("decode: tag=%d err=%v", decodedTag, err)
						}
						if container(&out, name).FieldByName(field.Name).Len() != 1 {
							t.Fatal("decoder omitted or misrouted field")
						}
						return nil
					})
					if err != nil || (j == tag && count != 1) || (j != tag && count != 0) {
						t.Fatalf("section %d count=%d err=%v", j, count, err)
					}
				}
			})
		}
	}
	if len(seen) != 35 {
		t.Fatal("record tag is not covered")
	}
}

