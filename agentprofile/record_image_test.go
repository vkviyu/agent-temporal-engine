	if err != nil {
		t.Fatal(err)
	}
	loaded, err := DecodeRecordImage(raw)
	if err != nil {
		t.Fatal(err)
	}
	ledger, err := loaded.Restore()
	if err != nil {
		t.Fatal(err)
	}
	if len(ledger.Snapshot().Lifecycle.Queries) != 50 {
		t.Fatal("records lost")
	}
	clear(raw[0].Raw)
	first, _ := image.Restore()
	second, _ := image.Restore()
	first.lifecycle.Queries[0].Input[0] = 'z'
	if second.lifecycle.Queries[0].Input[0] != 'x' {
		t.Fatal("restore aliases another ledger")
	}
	t.Logf("canonical record aggregate: %d bytes across %d records", image.Size(), len(raw))
