const derivationDomain = "ATE-DERIVATION\x00"
const maxDerivationNodes = 16384
const maxDerivationEdges = 65536

func derivationKey(object model.ObjectID) []byte {
	return []byte("ate/derivation/v1/" + string(object))
}

// Derivations are generated by the Packet/Summary reducer and committed with
// that record. Repeated uses of the same content add sources monotonically.
// A logical record and its raw output remain distinct identities.
func encodeDerivation(object model.ObjectID, sources []model.ObjectID) ([]byte, error) {
	if !model.ValidDigest(string(object)) || len(sources) == 0 || len(sources) > maxDerivationNodes {
		return nil, ErrInvalidStateData
	}
	out := codec.AppendUint([]byte(derivationDomain), 1)
	out, _ = codec.AppendString(out, string(object))
	out = codec.AppendUint(out, uint64(len(sources)))
	for i, source := range sources {
		if !model.ValidDigest(string(source)) || source == object || i > 0 && sources[i-1] >= source {
			return nil, ErrInvalidStateData
		}
		out, _ = codec.AppendString(out, string(source))
	}
	return out, nil
}

func decodeDerivation(raw []byte, object model.ObjectID) ([]model.ObjectID, error) {
	if !bytes.HasPrefix(raw, []byte(derivationDomain)) {
		return nil, ErrInvalidStateData
	}
	d := codec.NewDecoder(raw[len(derivationDomain):])
	version, err := d.Uint()
	if err != nil || version != 1 {
		return nil, ErrInvalidStateData
	}
	identity, err := d.String(64)
	if err != nil || identity != string(object) {
		return nil, ErrInvalidStateData
	}
	count, err := d.Uint()
	if err != nil || count == 0 || count > maxDerivationNodes || count > uint64(d.Remaining()/65) {
		return nil, ErrInvalidStateData
	}
	sources := make([]model.ObjectID, int(count))
	for i := range sources {
		id, err := d.String(64)
		if err != nil {
			return nil, ErrInvalidStateData
		}
		sources[i] = model.ObjectID(id)
	}
	canonical, err := encodeDerivation(object, sources)
	if err != nil || d.Done() != nil || !bytes.Equal(canonical, raw) {
		return nil, ErrInvalidStateData
	}
	return sources, nil
}

func loadDerivation(ctx context.Context, reader state.ObjectReader, root model.ObjectID, space model.SpaceID, object model.ObjectID) ([]model.ObjectID, error) {
	return loadDerivationAt(ctx, reader, root, space, space, derivationKey(object), object)
}

func loadDerivationAt(ctx context.Context, reader state.ObjectReader, root model.ObjectID, radixSpace, recordSpace model.SpaceID, key []byte, object model.ObjectID) ([]model.ObjectID, error) {
	id, found, err := state.Get(ctx, reader, radixSpace, root, key)
	if err != nil || !found {
		return nil, err
	}
	record, err := readObject(ctx, reader, id)
	if err != nil {
		return nil, err
	}
	value, err := readValue(record)
	if err != nil || record.Space != recordSpace || value.Kind != api.ValueBytes {
		return nil, ErrInvalidStateData
	}
	return decodeDerivation(value.Data, object)
}

func (e *Engine) prepareDerivedValue(ctx context.Context, req api.CommitRequest, digest model.ObjectID, txID model.TxID, lsn uint64, recorded *operationsRecord, key, raw []byte, links map[model.ObjectID][]model.ObjectID) (*commitPlan, error) {
	writes, err := e.appendDerivations(ctx, req.Space, []typedValueWrite{{key: key, raw: raw}}, links)
	if err != nil {
		return nil, err
	}
	return e.prepareTypedValues(ctx, req, digest, txID, lsn, recorded, writes)
}

func (e *Engine) appendDerivations(ctx context.Context, space model.SpaceID, writes []typedValueWrite, links map[model.ObjectID][]model.ObjectID) ([]typedValueWrite, error) {
	reader := &cursorReader{source: e.index}
	root, err := slotSpaceRoot(ctx, reader, e.roots.ExecutionKnowledge, space)
	if err != nil {
		return nil, err
	}
	for object, sources := range links {
		previous, err := loadDerivation(ctx, reader, root, space, object)
		if err != nil {
			return nil, err
		}
		sources = append(slices.Clone(sources), previous...)
		slices.Sort(sources)
		sources = slices.Compact(sources)
		sources = slices.DeleteFunc(sources, func(source model.ObjectID) bool { return source == "" || source == object })
		if len(sources) == 0 {
			continue
		}
		if len(sources) > maxDerivationNodes {
			return nil, storage.ErrLimit
		}
		data, err := encodeDerivation(object, sources)
		if err != nil {
			return nil, err
		}
		writes = append(writes, typedValueWrite{key: derivationKey(object), raw: data})
	}
	return writes, nil
}

// policyDependencyIDs computes one bounded closure across Memory/ExperiencePath
// and persisted Packet/Summary derivations. Only reachable adjacency records
// are read. No partition scan or historical snapshot decoding occurs here.
func (e *Engine) policyDependencyIDs(ctx context.Context, space model.SpaceID, policy memory.AccessPolicy, ids []model.ObjectID) ([]model.ObjectID, error) {
	pending, err := policy.DependencyClosure(ids)
	if err != nil {
		return nil, err
	}
	reader := &cursorReader{source: e.reader(ctx)}
	roots := e.readRoots(ctx)
	root, err := slotSpaceRoot(ctx, reader, roots.ExecutionKnowledge, space)
	if err != nil {
		return nil, err
	}
	seen := make(map[model.ObjectID]bool)
	edges := len(pending)
	for len(pending) > 0 {
		id := pending[len(pending)-1]
		pending = pending[:len(pending)-1]
		if seen[id] {
			continue
		}
		if len(seen) >= maxDerivationNodes || edges > maxDerivationEdges {
			return nil, storage.ErrLimit
		}
		seen[id] = true
		sources, err := loadDerivation(ctx, reader, root, space, id)
		if err != nil {
			return nil, err
		}
		control, err := loadDerivationAt(ctx, reader, roots.LiveControl, systemSpace, space, controlDerivationKey(space, id), id)
		if err != nil {
			return nil, err
		}
		sources = append(sources, control...)
		sources, err = policy.DependencyClosure(sources)
		if err != nil {
			return nil, err
		}
		edges += len(sources)
		if edges > maxDerivationEdges {
			return nil, storage.ErrLimit
		}
		pending = append(pending, sources...)
	}
	out := make([]model.ObjectID, 0, len(seen))
	for id := range seen {
		out = append(out, id)
	}
	slices.Sort(out)
	return out, nil
}

func (e *Engine) checkPolicyIDs(ctx context.Context, space model.SpaceID, ids []model.ObjectID, purpose memory.AccessPurpose) error {
	policy, err := e.readPolicy(ctx, space)
	if err != nil {
		return err
	}
	dependencies, err := e.policyDependencyIDs(ctx, space, policy, ids)
	if err != nil {
		return err
	}
	return policy.Check(dependencies, purpose)
}
